export interface Photo {
  src: string;
  alt: string;
  caption: string;
}

export interface AtlasStop {
  id: string;
  title: string;
  location: string;
  region: string;
  when: string;
  lat: number;
  lon: number;
  summary: string;
  palette: string[];
  photos: Photo[];
}

function createPhotoSet(
  paths: string[],
  label: string,
  caption: string
): Photo[] {
  return paths.map((src, index) => ({
    src,
    alt: `${label} photo ${index + 1}`,
    caption,
  }));
}

